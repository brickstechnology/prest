// miniship (miniship-cloud#1303): the Supabase SDK's writes, POST, PATCH and
// DELETE on /rest/v1/{table}, against a live Postgres. Each subject sends the
// request the SDK's postgrest-js sends for one call (its method, its query
// string, its Prefer and Content-Profile headers) and then asks the Database
// what the write did, directly, as the superuser.
//
// The public repository's docker/tests/database-sdk.test.ts asks the same
// questions with the real SDK through the gateway; these are the ones a Go
// test can ask of rest alone, among them the row quota with a small ceiling.

