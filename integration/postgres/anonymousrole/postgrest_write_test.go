const notes = "rest_pgw_notes"

// stageNotes makes the table the writes change. A User owns the rows whose
// owner is their token's sub; the row rule lets them read, insert, change and
// remove those and no others; the reader (the anonymous role) holds no write
// grant at all; service_role passes the rules.
//
//	id  title  owner
//	1   a1     userA
//	2   a2     userA
//	3   b1     userB
//	4   b2     userB
func stageNotes(t *testing.T, db *sql.DB) {
	t.Helper()
	stagePostgREST(t, db)
	drop := fmt.Sprintf(`DROP TABLE IF EXISTS public.%s;`, notes)
	exec(t, db, drop)
	t.Cleanup(func() { exec(t, db, drop) })
	exec(t, db, fmt.Sprintf(`
		CREATE TABLE public.%[1]s (
			id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			title text NOT NULL UNIQUE,
			body text DEFAULT 'empty',
			owner text,
			tags text[],
			meta jsonb,
			created timestamptz DEFAULT now());
		INSERT INTO public.%[1]s (title, owner) VALUES
			('a1', '%[5]s'), ('a2', '%[5]s'), ('b1', '%[6]s'), ('b2', '%[6]s');
		ALTER TABLE public.%[1]s ENABLE ROW LEVEL SECURITY;
		CREATE POLICY a_user_owns ON public.%[1]s FOR ALL TO %[2]s
			USING (owner = current_setting('request.jwt.claim.sub', true))
			WITH CHECK (owner = current_setting('request.jwt.claim.sub', true));
		GRANT SELECT, INSERT, UPDATE, DELETE ON public.%[1]s TO %[2]s, %[3]s;
		GRANT SELECT ON public.%[1]s TO %[4]s;
	`, notes, signedIn, service, reader, userA, userB))
}

// theNotes is what the table holds, as the superuser sees it, one string a row.
func theNotes(t *testing.T, db *sql.DB) []string {
	t.Helper()
	rows, err := db.Query(fmt.Sprintf(`SELECT id || ':' || title || ':' || coalesce(owner, '-') FROM public.%s ORDER BY id`, notes))
	require.NoError(t, err)
	defer rows.Close()
	out := []string{}
	for rows.Next() {
		var line string
		require.NoError(t, rows.Scan(&line))
		out = append(out, line)
	}
	return out
}

// send sends one SDK-shaped write for the Project, with a JSON body.
func send(t *testing.T, server *httptest.Server, method, path, bearer string, headers map[string]string, body string) (int, http.Header, string) {
	t.Helper()
	req, err := http.NewRequest(method, server.URL+path, strings.NewReader(body))
	require.NoError(t, err)
	req.Header.Set(projectHeader, alias)
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Content-Profile", "public")
	if bearer != "" {
		req.Header.Set("Authorization", "Bearer "+bearer)
	}
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	resp, err := server.Client().Do(req)
	require.NoError(t, err)
	defer resp.Body.Close()
	var out strings.Builder
	buf := make([]byte, 4096)
	for {
		n, err := resp.Body.Read(buf)
		out.Write(buf[:n])
		if err != nil {
			break
		}
	}
	return resp.StatusCode, resp.Header, out.String()
}

func refusalOf(t *testing.T, body string) map[string]any {
	t.Helper()
	var answer map[string]any
	require.NoError(t, json.Unmarshal([]byte(body), &answer), body)
	for _, field := range []string{"code", "message", "details", "hint"} {
		require.Contains(t, answer, field, body)
	}
	return answer
}

type notesFixture struct {
	db   *sql.DB
	rest *httptest.Server
	a, b string
	anon string
	svc  string
}

func newNotesFixture(t *testing.T, with ...func(*config.Prest)) notesFixture {
	t.Helper()
	cfg, db := needsPostgres(t)
	stageNotes(t, db)
	install := newInstall(t)
	pool := newProjectPool(t, alias)
	return notesFixture{
		db:   db,
		rest: restForTheSDK(t, cfg, install, pool, with...),
		a:    userToken(t, pool.private, userA),
		b:    userToken(t, pool.private, userB),
		anon: projectToken(t, install.private, reader, alias),
		svc:  projectToken(t, install.private, service, alias),
	}
}

func TestPostgRESTWrite_insertReturnsMinimalOrTheRows(t *testing.T) {
	f := newNotesFixture(t)
	path := "/rest/v1/" + notes

	// insert() with no select(). Expected: 201, no body, and the row is there
	// with its defaults.
	status, _, body := send(t, f.rest, http.MethodPost, path, f.a, nil, fmt.Sprintf(`{"title":"a3","owner":"%s"}`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.Empty(t, body)
	require.Equal(t, []string{"1:a1:" + userA, "2:a2:" + userA, "3:b1:" + userB, "4:b2:" + userB, "5:a3:" + userA}, theNotes(t, f.db))

	// insert().select(). Expected: 201 and the row, with the id and the body
	// the Database gave it.
	status, headers, body := send(t, f.rest, http.MethodPost, path+"?select=id,title,body", f.a,
		map[string]string{"Prefer": "return=representation"}, fmt.Sprintf(`{"title":"a4","owner":"%s"}`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.JSONEq(t, `[{"id":6,"title":"a4","body":"empty"}]`, body)
	require.Equal(t, "*/*", headers.Get("Content-Range"))

	// A bulk insert, as the SDK sends one: columns names the union of the keys,
	// a row that omits one gets null, and count=exact is answered.
	status, headers, body = send(t, f.rest, http.MethodPost, path+`?columns="title","owner","body"&select=title,body,owner`, f.a,
		map[string]string{"Prefer": "return=representation, count=exact"},
		fmt.Sprintf(`[{"title":"a5","owner":"%[1]s","body":"five"},{"title":"a6","owner":"%[1]s"}]`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.JSONEq(t, fmt.Sprintf(`[{"title":"a5","body":"five","owner":%[1]q},{"title":"a6","body":null,"owner":%[1]q}]`, userA), body)
	require.Equal(t, "*/2", headers.Get("Content-Range"))

	// missing=default: the same omission takes the column's default.
	status, _, body = send(t, f.rest, http.MethodPost, path+`?columns="title","owner","body"&select=title,body`, f.a,
		map[string]string{"Prefer": "return=representation, missing=default"},
		fmt.Sprintf(`[{"title":"a7","owner":"%[1]s","body":"seven"},{"title":"a8","owner":"%[1]s"}]`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.JSONEq(t, `[{"title":"a7","body":"seven"},{"title":"a8","body":"empty"}]`, body)

	// Values are read as their column's type: an array, jsonb and a timestamp.
	status, _, body = send(t, f.rest, http.MethodPost, path+"?select=tags,meta,created", f.a,
		map[string]string{"Prefer": "return=representation"},
		fmt.Sprintf(`{"title":"typed","owner":"%s","tags":["x","y"],"meta":{"k":[1,2]},"created":"2026-01-02T03:04:05Z"}`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.JSONEq(t, `[{"tags":["x","y"],"meta":{"k":[1,2]},"created":"2026-01-02T03:04:05+00:00"}]`, body)

	// single(): one row, as an object.
	status, _, body = send(t, f.rest, http.MethodPost, path+"?select=title", f.a,
		map[string]string{"Prefer": "return=representation", "Accept": "application/vnd.pgrst.object+json"},
		fmt.Sprintf(`{"title":"one","owner":"%s"}`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.JSONEq(t, `{"title":"one"}`, body)
}

func TestPostgRESTWrite_updateAndDeleteChangeTheRowsTheFiltersMatch(t *testing.T) {
	f := newNotesFixture(t)
	path := "/rest/v1/" + notes

	// update().eq(). Expected: 204, count in Content-Range, one row changed.
	status, headers, body := send(t, f.rest, http.MethodPatch, path+"?id=eq.1", f.a, map[string]string{"Prefer": "count=exact"}, `{"body":"edited"}`)
	require.Equal(t, http.StatusNoContent, status, body)
	require.Equal(t, "0-0/1", headers.Get("Content-Range"))

	// update().in().select(). Expected: 200 and both rows, changed.
	status, headers, body = send(t, f.rest, http.MethodPatch, path+"?id=in.(1,2)&select=id,body&order=id", f.a,
		map[string]string{"Prefer": "return=representation"}, `{"body":"twice"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":1,"body":"twice"},{"id":2,"body":"twice"}]`, body)
	require.Equal(t, "0-1/*", headers.Get("Content-Range"))

	// A filter that matches nothing. Expected: 200 and [], nothing changed.
	status, headers, body = send(t, f.rest, http.MethodPatch, path+"?id=eq.99&select=id", f.a,
		map[string]string{"Prefer": "return=representation"}, `{"body":"never"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[]`, body)
	require.Equal(t, "*/*", headers.Get("Content-Range"))

	// The SDK's null clears a column.
	status, _, body = send(t, f.rest, http.MethodPatch, path+"?id=eq.2&select=body", f.a, map[string]string{"Prefer": "return=representation"}, `{"body":null}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"body":null}]`, body)

	// delete().eq().select(). Expected: 200 and the row; then it is gone.
	status, headers, body = send(t, f.rest, http.MethodDelete, path+"?id=eq.2&select=id,title", f.a,
		map[string]string{"Prefer": "return=representation, count=exact"}, "")
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":2,"title":"a2"}]`, body)
	require.Equal(t, "*/1", headers.Get("Content-Range"))

	// delete() with no select. Expected: 204.
	status, _, body = send(t, f.rest, http.MethodDelete, path+"?title=eq.a1", f.a, nil, "")
	require.Equal(t, http.StatusNoContent, status, body)
	require.Equal(t, []string{"3:b1:" + userB, "4:b2:" + userB}, theNotes(t, f.db))
}

func TestPostgRESTWrite_upsertInsertsAndMergesAndIgnores(t *testing.T) {
	f := newNotesFixture(t)
	path := "/rest/v1/" + notes
	merge := map[string]string{"Prefer": "resolution=merge-duplicates, return=representation"}

	// upsert() with a new row and an existing one, on the primary key.
	// Expected: 201 (a row was new), both rows come back, one changed.
	status, _, body := send(t, f.rest, http.MethodPost, path+`?columns="id","title","owner"&select=id,title&order=id`, f.a, merge,
		fmt.Sprintf(`[{"id":1,"title":"a1 merged","owner":"%[1]s"},{"id":10,"title":"ten","owner":"%[1]s"}]`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.JSONEq(t, `[{"id":1,"title":"a1 merged"},{"id":10,"title":"ten"}]`, body)

	// upsert() of rows that all exist. Expected: 200, and they are changed.
	status, _, body = send(t, f.rest, http.MethodPost, path+`?columns="id","title","owner"&select=id,title&order=id`, f.a, merge,
		fmt.Sprintf(`[{"id":1,"title":"a1 again","owner":"%[1]s"},{"id":10,"title":"ten again","owner":"%[1]s"}]`, userA))
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":1,"title":"a1 again"},{"id":10,"title":"ten again"}]`, body)

	// onConflict names another unique column.
	status, _, body = send(t, f.rest, http.MethodPost, path+"?on_conflict=title&select=id,body", f.a, merge,
		fmt.Sprintf(`{"title":"a2","body":"by title","owner":"%s"}`, userA))
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":2,"body":"by title"}]`, body)

	// ignoreDuplicates. Expected: the existing row is left as it was, and only
	// the new row comes back.
	ignore := map[string]string{"Prefer": "resolution=ignore-duplicates, return=representation"}
	status, _, body = send(t, f.rest, http.MethodPost, path+`?columns="id","title","owner"&select=id,title&order=id`, f.a, ignore,
		fmt.Sprintf(`[{"id":2,"title":"must not change","owner":"%[1]s"},{"id":11,"title":"eleven","owner":"%[1]s"}]`, userA))
	require.Equal(t, http.StatusCreated, status, body)
	require.JSONEq(t, `[{"id":11,"title":"eleven"}]`, body)
	require.Equal(t, []string{
		"1:a1 again:" + userA, "2:a2:" + userA, "3:b1:" + userB, "4:b2:" + userB,
		"10:ten again:" + userA, "11:eleven:" + userA,
	}, theNotes(t, f.db))
}

func TestPostgRESTWrite_aWriteWithNoFilterIsRefusedAndChangesNothing(t *testing.T) {
	f := newNotesFixture(t)
	before := theNotes(t, f.db)

	for method, verb := range map[string]string{http.MethodPatch: "UPDATE", http.MethodDelete: "DELETE"} {
		for _, bearer := range []string{f.a, f.svc} {
			status, _, body := send(t, f.rest, method, "/rest/v1/"+notes, bearer, map[string]string{"Prefer": "return=representation"}, `{"body":"all"}`)
			require.Equal(t, http.StatusBadRequest, status, "%s: %s", method, body)
			refusal := refusalOf(t, body)
			require.Equal(t, "21000", refusal["code"])
			require.Equal(t, verb+" requires a WHERE clause", refusal["message"])
		}
	}
	// A filter that is only a sort, or select, is no filter.
	status, _, body := send(t, f.rest, http.MethodDelete, "/rest/v1/"+notes+"?select=id&order=id", f.svc, nil, "")
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, before, theNotes(t, f.db))
}

func TestPostgRESTWrite_theRowRulesDecideEachWrite(t *testing.T) {
	f := newNotesFixture(t)
	path := "/rest/v1/" + notes
	before := theNotes(t, f.db)

	// A User changes and removes another User's row. Expected: the rule hides
	// the row from the write, so no row matches; nothing changes, and the
	// answer says so.
	status, _, body := send(t, f.rest, http.MethodPatch, path+"?id=eq.3&select=id", f.a, map[string]string{"Prefer": "return=representation"}, `{"body":"mine now"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[]`, body)
	status, _, body = send(t, f.rest, http.MethodDelete, path+"?id=eq.3&select=id", f.a, map[string]string{"Prefer": "return=representation"}, "")
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[]`, body)
	require.Equal(t, before, theNotes(t, f.db))

	// A User inserts a row for another User, and moves their own row to one.
	// Expected: refused by the rule's check, 403 and the Database's own words.
	status, _, body = send(t, f.rest, http.MethodPost, path, f.a, nil, fmt.Sprintf(`{"title":"forged","owner":"%s"}`, userB))
	require.Equal(t, http.StatusForbidden, status, body)
	refusal := refusalOf(t, body)
	require.Equal(t, "42501", refusal["code"])
	require.Contains(t, refusal["message"], "new row violates row-level security policy")
	status, _, body = send(t, f.rest, http.MethodPatch, path+"?id=eq.1", f.a, nil, fmt.Sprintf(`{"owner":"%s"}`, userB))
	require.Equal(t, http.StatusForbidden, status, body)
	require.Equal(t, "42501", refusalOf(t, body)["code"])

	// A signed-out caller holds no write grant. Expected: 401, 42501.
	status, _, body = send(t, f.rest, http.MethodPost, path, f.anon, nil, `{"title":"anonymous"}`)
	require.Equal(t, http.StatusUnauthorized, status, body)
	require.Equal(t, "42501", refusalOf(t, body)["code"])
	status, _, body = send(t, f.rest, http.MethodDelete, path+"?id=eq.1", "", nil, "")
	require.Less(t, status, 500)
	require.NotEqual(t, http.StatusNoContent, status, body)

	// The secret key passes the rules, on purpose.
	status, _, body = send(t, f.rest, http.MethodPatch, path+"?id=eq.3&select=id,body", f.svc, map[string]string{"Prefer": "return=representation"}, `{"body":"by the server"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":3,"body":"by the server"}]`, body)
	require.Equal(t, before, theNotes(t, f.db))
}

func TestPostgRESTWrite_aConstraintReturnsTheDatabasesWordsAndLeavesNoPartialChange(t *testing.T) {
	f := newNotesFixture(t)
	path := "/rest/v1/" + notes
	before := theNotes(t, f.db)

	// A unique violation on the second row of a bulk insert, as a User.
	// Expected: 409, 23505, the Database's message; the first row is not there.
	// The Database withholds details of a row from a role the row rules bind.
	status, _, body := send(t, f.rest, http.MethodPost, path+`?columns="title","owner"`, f.a, nil,
		fmt.Sprintf(`[{"title":"fresh","owner":"%[1]s"},{"title":"a1","owner":"%[1]s"}]`, userA))
	require.Equal(t, http.StatusConflict, status, body)
	refusal := refusalOf(t, body)
	require.Equal(t, "23505", refusal["code"])
	require.Contains(t, refusal["message"], "duplicate key value violates unique constraint")
	require.Equal(t, before, theNotes(t, f.db))

	// The same as the secret key, which no row rule binds. Expected: the
	// Database's details too, naming the key.
	status, _, body = send(t, f.rest, http.MethodPost, path+`?columns="title","owner"`, f.svc, nil, `[{"title":"fresh"},{"title":"a1"}]`)
	require.Equal(t, http.StatusConflict, status, body)
	refusal = refusalOf(t, body)
	require.Equal(t, "23505", refusal["code"])
	require.Contains(t, refusal["details"], "Key (title)=(a1) already exists")
	require.Equal(t, before, theNotes(t, f.db))

	// A not-null violation: 400, 23502, and the details show the row.
	status, _, body = send(t, f.rest, http.MethodPost, path, f.svc, nil, `{"owner":"nobody"}`)
	require.Equal(t, http.StatusBadRequest, status, body)
	refusal = refusalOf(t, body)
	require.Equal(t, "23502", refusal["code"])
	require.Contains(t, refusal["message"], `"title"`)
	require.Contains(t, refusal["details"], "Failing row contains")

	// A value of the wrong type: 400, 22P02.
	status, _, body = send(t, f.rest, http.MethodPost, path, f.a, nil, fmt.Sprintf(`{"id":"not a number","title":"x","owner":"%s"}`, userA))
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, "22P02", refusalOf(t, body)["code"])

	// An update that breaks the constraint on its second row.
	status, _, body = send(t, f.rest, http.MethodPatch, path+"?id=in.(1,2)", f.a, nil, `{"title":"same"}`)
	require.Equal(t, http.StatusConflict, status, body)
	require.Equal(t, "23505", refusalOf(t, body)["code"])

	// A column the table lacks: 400, PGRST204. A table that is not there: 404.
	status, _, body = send(t, f.rest, http.MethodPost, path, f.a, nil, `{"no_such_column":1}`)
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, "PGRST204", refusalOf(t, body)["code"])
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rest_pgw_absent", f.a, nil, `{"a":1}`)
	require.Equal(t, http.StatusNotFound, status, body)
	require.Equal(t, "PGRST205", refusalOf(t, body)["code"])

	// A body that is not JSON objects.
	for _, bad := range []string{``, `not json`, `42`, `[1,2]`} {
		status, _, body = send(t, f.rest, http.MethodPost, path, f.a, nil, bad)
		require.Equal(t, http.StatusBadRequest, status, bad)
		require.Equal(t, "PGRST102", refusalOf(t, body)["code"], bad)
	}
	require.Equal(t, before, theNotes(t, f.db))
}

func TestPostgRESTWrite_aWriteOverTheRowQuotaIsRefusedWholeAndChangesNothing(t *testing.T) {
	f := newNotesFixture(t, func(c *config.Prest) { c.PGMaxPageSize = 3 })
	path := "/rest/v1/" + notes
	before := theNotes(t, f.db)

	// An insert of four rows with a quota of three. Expected: 400, MS104,
	// refused before the Database is asked; no row.
	status, _, body := send(t, f.rest, http.MethodPost, path+`?columns="title","owner"`, f.svc, nil,
		`[{"title":"q1"},{"title":"q2"},{"title":"q3"},{"title":"q4"}]`)
	require.Equal(t, http.StatusBadRequest, status, body)
	refusal := refusalOf(t, body)
	require.Equal(t, "MS104", refusal["code"])
	require.Contains(t, refusal["details"], "at most 3 rows a write")

	// An update and a delete that match four rows. Expected: the same
	// refusal, after the statement ran and was rolled back; no row changed.
	status, _, body = send(t, f.rest, http.MethodPatch, path+"?id=gt.0", f.svc, map[string]string{"Prefer": "return=representation"}, `{"body":"all four"}`)
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, "MS104", refusalOf(t, body)["code"])
	status, _, body = send(t, f.rest, http.MethodDelete, path+"?id=gt.0", f.svc, nil, "")
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, "MS104", refusalOf(t, body)["code"])
	require.Equal(t, before, theNotes(t, f.db))

	// An upsert whose rows all merge still counts the rows it changes.
	status, _, body = send(t, f.rest, http.MethodPost, path+`?columns="id","title","owner"`, f.svc,
		map[string]string{"Prefer": "resolution=merge-duplicates"},
		`[{"id":1,"title":"m1"},{"id":2,"title":"m2"},{"id":3,"title":"m3"},{"id":4,"title":"m4"}]`)
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, before, theNotes(t, f.db))

	// Exactly the quota is allowed.
	status, _, body = send(t, f.rest, http.MethodPatch, path+"?id=lte.3", f.svc, nil, `{"body":"three"}`)
	require.Equal(t, http.StatusNoContent, status, body)

	// A body longer than rest reads is refused by its size (MS105).
	long := `{"title":"` + strings.Repeat("x", 9<<20) + `"}`
	status, _, body = send(t, f.rest, http.MethodPost, path, f.svc, nil, long)
	require.Equal(t, http.StatusRequestEntityTooLarge, status)
	require.Equal(t, "MS105", refusalOf(t, body)["code"])
}

func TestPostgRESTWrite_thePreferencesHoldTheWriteToWhatTheCallerAsked(t *testing.T) {
	f := newNotesFixture(t)
	path := "/rest/v1/" + notes
	before := theNotes(t, f.db)

	// single() on a write that changes two rows. Expected: 406, PGRST116, and
	// the write is rolled back.
	status, _, body := send(t, f.rest, http.MethodPatch, path+"?id=in.(1,2)&select=id", f.a,
		map[string]string{"Prefer": "return=representation", "Accept": "application/vnd.pgrst.object+json"}, `{"body":"two"}`)
	require.Equal(t, http.StatusNotAcceptable, status, body)
	refusal := refusalOf(t, body)
	require.Equal(t, "PGRST116", refusal["code"])
	require.Equal(t, "The result contains 2 rows", refusal["details"])

	// maxAffected(1). Expected: 400, PGRST124, rolled back.
	status, _, body = send(t, f.rest, http.MethodDelete, path+"?id=in.(1,2)", f.a,
		map[string]string{"Prefer": "handling=strict, max-affected=1"}, "")
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, "PGRST124", refusalOf(t, body)["code"])

	// rollback(). Expected: the answer a commit would give, and no change.
	status, _, body = send(t, f.rest, http.MethodPatch, path+"?id=eq.1&select=body", f.a,
		map[string]string{"Prefer": "return=representation, tx=rollback"}, `{"body":"rolled back"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"body":"rolled back"}]`, body)
	require.Equal(t, before, theNotes(t, f.db))

	// Another schema. Expected: 406, PGRST106.
	status, _, body = send(t, f.rest, http.MethodPost, path, f.a, map[string]string{"Content-Profile": "private"}, `{"title":"x"}`)
	require.Equal(t, http.StatusNotAcceptable, status, body)
	require.Equal(t, "PGRST106", refusalOf(t, body)["code"])
	require.Equal(t, "Invalid schema: private", refusalOf(t, body)["message"])
	require.Equal(t, "Only the following schemas are exposed: public", refusalOf(t, body)["hint"])

	// A body rest does not read. Expected: 400, PGRST102, as PostgREST 14
	// answers a Content-Type it has no payload parser for.
	status, _, body = send(t, f.rest, http.MethodPost, path, f.a, map[string]string{"Content-Type": "application/xml"}, "<a/>")
	require.Equal(t, http.StatusBadRequest, status, body)
	got := refusalOf(t, body)
	require.Equal(t, "PGRST102", got["code"])
	require.Equal(t, "Content-Type not acceptable: application/xml", got["message"])
}

