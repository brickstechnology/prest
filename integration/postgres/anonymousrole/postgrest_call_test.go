// shelf is the table the functions read and change: a User sees the rows whose
// owner is their token's sub.
const shelf = "rest_pgc_shelf"

// stageFunctions makes the table and the functions the subjects call.
//
//	rest_pgc_shelf    id  title  owner   (1 a1 userA) (2 a2 userA) (3 b1 userB) (4 b2 userB)
//	rest_pgc_add      (a int, b int) -> int            IMMUTABLE
//	rest_pgc_hello    () -> text
//	rest_pgc_greet    (name text DEFAULT 'world', shout boolean DEFAULT false) -> text
//	rest_pgc_nums     (n int) -> SETOF int
//	rest_pgc_titles   (min_id int) -> TABLE(id int, title text)
//	rest_pgc_mine     () -> SETOF rest_pgc_shelf       STABLE, runs as the caller
//	rest_pgc_first    (min_id int) -> rest_pgc_shelf   one row of the table
//	rest_pgc_pair     (n int, OUT low int, OUT high int)  one row of OUT arguments
//	rest_pgc_nothing  () -> void
//	rest_pgc_rename   (item int, new_title text) -> int  VOLATILE, writes one row
//	rest_pgc_grow     (n int) -> int                     VOLATILE, inserts n rows
//	rest_pgc_stamp    () -> text                         VOLATILE, writes nothing
//	rest_pgc_same     (a int) and (a bigint)             overloads the names cannot tell apart
//	rest_pgc_both     (a int) and (a int, b int)         overloads the names tell apart
//	rest_pgc_echo     (j jsonb) -> jsonb
//	rest_pgc_unnamed  (json) -> json                     one unnamed argument
//	rest_pgc_sum      (VARIADIC nums int[]) -> int
//	rest_pgc_whoami   () -> text                         the token's sub
//	rest_pgc_fail     () -> void                         raises
//	rest_pgc_status   () -> void                         raises SQLSTATE PT418
//	rest_pgc_secret   () -> text                         the reader may not run it
func stageFunctions(t *testing.T, db *sql.DB) {
	t.Helper()
	stagePostgREST(t, db)
	drop := fmt.Sprintf(`
		DROP TABLE IF EXISTS public.%[1]s CASCADE;
		DROP FUNCTION IF EXISTS public.rest_pgc_add(int, int), public.rest_pgc_hello(),
			public.rest_pgc_greet(text, boolean), public.rest_pgc_nums(int), public.rest_pgc_titles(int),
			public.rest_pgc_mine(), public.rest_pgc_first(int), public.rest_pgc_pair(int),
			public.rest_pgc_nothing(), public.rest_pgc_rename(int, text), public.rest_pgc_grow(int),
			public.rest_pgc_stamp(), public.rest_pgc_same(int), public.rest_pgc_same(bigint),
			public.rest_pgc_both(int), public.rest_pgc_both(int, int), public.rest_pgc_echo(jsonb),
			public.rest_pgc_unnamed(json), public.rest_pgc_sum(int[]), public.rest_pgc_whoami(),
			public.rest_pgc_fail(), public.rest_pgc_status(), public.rest_pgc_secret();`, shelf)
	exec(t, db, drop)
	t.Cleanup(func() { exec(t, db, drop) })
	exec(t, db, fmt.Sprintf(`
		CREATE TABLE public.%[1]s (
			id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title text NOT NULL, owner text);
		INSERT INTO public.%[1]s (title, owner) VALUES ('a1', '%[5]s'), ('a2', '%[5]s'), ('b1', '%[6]s'), ('b2', '%[6]s');
		ALTER TABLE public.%[1]s ENABLE ROW LEVEL SECURITY;
		CREATE POLICY a_user_owns ON public.%[1]s FOR ALL TO %[2]s
			USING (owner = current_setting('request.jwt.claim.sub', true))
			WITH CHECK (owner = current_setting('request.jwt.claim.sub', true));
		GRANT SELECT, INSERT, UPDATE, DELETE ON public.%[1]s TO %[2]s, %[3]s;
		GRANT SELECT ON public.%[1]s TO %[4]s;

		CREATE FUNCTION public.rest_pgc_add(a int, b int) RETURNS int LANGUAGE sql IMMUTABLE AS $$ SELECT a + b $$;
		CREATE FUNCTION public.rest_pgc_hello() RETURNS text LANGUAGE sql AS $$ SELECT 'hello' $$;
		CREATE FUNCTION public.rest_pgc_greet(name text DEFAULT 'world', shout boolean DEFAULT false) RETURNS text
			LANGUAGE sql AS $$ SELECT CASE WHEN shout THEN upper('hello ' || name) ELSE 'hello ' || name END $$;
		CREATE FUNCTION public.rest_pgc_nums(n int) RETURNS SETOF int LANGUAGE sql AS $$ SELECT generate_series(1, n) $$;
		CREATE FUNCTION public.rest_pgc_titles(min_id int) RETURNS TABLE(id int, title text) LANGUAGE sql STABLE
			AS $$ SELECT s.id, s.title FROM public.%[1]s s WHERE s.id >= min_id $$;
		CREATE FUNCTION public.rest_pgc_mine() RETURNS SETOF public.%[1]s LANGUAGE sql STABLE AS $$ SELECT * FROM public.%[1]s $$;
		CREATE FUNCTION public.rest_pgc_first(min_id int) RETURNS public.%[1]s LANGUAGE sql STABLE
			AS $$ SELECT s FROM public.%[1]s s WHERE s.id >= min_id ORDER BY s.id LIMIT 1 $$;
		CREATE FUNCTION public.rest_pgc_pair(n int, OUT low int, OUT high int) LANGUAGE sql AS $$ SELECT n - 1, n + 1 $$;
		CREATE FUNCTION public.rest_pgc_nothing() RETURNS void LANGUAGE sql AS $$ SELECT 1 $$;
		CREATE FUNCTION public.rest_pgc_rename(item int, new_title text) RETURNS int LANGUAGE sql
			AS $$ WITH changed AS (UPDATE public.%[1]s SET title = new_title WHERE id = item RETURNING 1) SELECT count(*)::int FROM changed $$;
		CREATE FUNCTION public.rest_pgc_grow(n int) RETURNS int LANGUAGE sql
			AS $$ WITH added AS (INSERT INTO public.%[1]s (title, owner)
			      SELECT 'grown ' || g, current_setting('request.jwt.claim.sub', true) FROM generate_series(1, n) g RETURNING 1)
			      SELECT count(*)::int FROM added $$;
		CREATE FUNCTION public.rest_pgc_stamp() RETURNS text LANGUAGE sql VOLATILE AS $$ SELECT 'stamped' $$;
		CREATE FUNCTION public.rest_pgc_same(a int) RETURNS text LANGUAGE sql AS $$ SELECT 'int' $$;
		CREATE FUNCTION public.rest_pgc_same(a bigint) RETURNS text LANGUAGE sql AS $$ SELECT 'bigint' $$;
		CREATE FUNCTION public.rest_pgc_both(a int) RETURNS text LANGUAGE sql AS $$ SELECT 'one' $$;
		CREATE FUNCTION public.rest_pgc_both(a int, b int) RETURNS text LANGUAGE sql AS $$ SELECT 'two' $$;
		CREATE FUNCTION public.rest_pgc_echo(j jsonb) RETURNS jsonb LANGUAGE sql AS $$ SELECT j $$;
		CREATE FUNCTION public.rest_pgc_unnamed(json) RETURNS json LANGUAGE sql AS $$ SELECT $1 $$;
		CREATE FUNCTION public.rest_pgc_sum(VARIADIC nums int[]) RETURNS int LANGUAGE sql AS $$ SELECT sum(n)::int FROM unnest(nums) n $$;
		CREATE FUNCTION public.rest_pgc_whoami() RETURNS text LANGUAGE sql STABLE AS $$ SELECT current_setting('request.jwt.claim.sub', true) $$;
		CREATE FUNCTION public.rest_pgc_fail() RETURNS void LANGUAGE plpgsql
			AS $$ BEGIN RAISE EXCEPTION 'no way' USING DETAIL = 'because', HINT = 'try again'; END $$;
		CREATE FUNCTION public.rest_pgc_status() RETURNS void LANGUAGE plpgsql
			AS $$ BEGIN RAISE EXCEPTION 'a teapot' USING ERRCODE = 'PT418'; END $$;
		CREATE FUNCTION public.rest_pgc_secret() RETURNS text LANGUAGE sql AS $$ SELECT 'secret' $$;
		REVOKE EXECUTE ON FUNCTION public.rest_pgc_secret() FROM PUBLIC;
		GRANT EXECUTE ON FUNCTION public.rest_pgc_secret() TO %[2]s, %[3]s;
	`, shelf, signedIn, service, reader, userA, userB))
}

// theShelf is what the table holds, as the superuser sees it.
func theShelf(t *testing.T, db *sql.DB) []string {
	t.Helper()
	rows, err := db.Query(fmt.Sprintf(`SELECT id || ':' || title FROM public.%s ORDER BY id`, shelf))
	require.NoError(t, err)
	defer rows.Close()
	out := []string{}
	for rows.Next() {
		var line string
		require.NoError(t, rows.Scan(&line))
		out = append(out, line)
	}
	return out
}

type callFixture struct {
	db   *sql.DB
	rest *httptest.Server
	a, b string
	anon string
	svc  string
}

func newCallFixture(t *testing.T, with ...func(*config.Prest)) callFixture {
	t.Helper()
	cfg, db := needsPostgres(t)
	stageFunctions(t, db)
	install := newInstall(t)
	pool := newProjectPool(t, alias)
	return callFixture{
		db:   db,
		rest: restForTheSDK(t, cfg, install, pool, with...),
		a:    userToken(t, pool.private, userA),
		b:    userToken(t, pool.private, userB),
		anon: token(t, install.private, reader),
		svc:  token(t, install.private, service),
	}
}

func TestPostgRESTCall_aFunctionThatReturnsAValue(t *testing.T) {
	f := newCallFixture(t)

	// rpc('rest_pgc_add', { a: 1, b: 2 }). Expected: 200 and the bare value.
	status, headers, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_add", f.a, nil, `{"a":1,"b":2}`)
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, "3", body)
	require.Contains(t, headers.Get("Content-Type"), "application/json")
	require.Equal(t, "0-0/*", headers.Get("Content-Range"))

	// The same with get: true. The values arrive as text and are read as the
	// arguments' types.
	status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/rpc/rest_pgc_add?a=40&b=2", f.a, nil, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, "42", body)

	// A function with no arguments, an empty body, and a string.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_hello", f.anon, nil, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, `"hello"`, body)

	// Arguments that are left out take their defaults; the ones sent do not.
	for call, want := range map[string]string{`{}`: `"hello world"`, `{"name":"you"}`: `"hello you"`, `{"name":"you","shout":true}`: `"HELLO YOU"`} {
		status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_greet", f.a, nil, call)
		require.Equal(t, http.StatusOK, status, body)
		require.Equal(t, want, body, call)
	}
	status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/rpc/rest_pgc_greet?shout=true", f.a, nil, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, `"HELLO WORLD"`, body)

	// head: true. Expected: the status and the headers and no body.
	status, headers, body = send(t, f.rest, http.MethodHead, "/rest/v1/rpc/rest_pgc_add?a=1&b=1", f.a, map[string]string{"Prefer": "count=exact"}, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Empty(t, body)
	require.Equal(t, "0-0/1", headers.Get("Content-Range"))

	// A function that returns nothing is 204.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_nothing", f.a, nil, "")
	require.Equal(t, http.StatusNoContent, status, body)
	require.Empty(t, body)
}

func TestPostgRESTCall_aFunctionThatReturnsRows(t *testing.T) {
	f := newCallFixture(t)

	// A set of scalars is an array of them.
	status, headers, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_nums", f.a, nil, `{"n":4}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[1,2,3,4]`, body)
	require.Equal(t, "0-3/*", headers.Get("Content-Range"))

	// A function that returns a table is an array of objects, and takes the
	// read's filters, order, limit and offset, and a count, over its rows.
	titles := "/rest/v1/rpc/rest_pgc_titles"
	status, headers, body = send(t, f.rest, http.MethodPost, titles+"?id=gt.1&order=id.desc&limit=2&offset=1", f.svc,
		map[string]string{"Prefer": "count=exact"}, `{"min_id":1}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":3,"title":"b1"},{"id":2,"title":"a2"}]`, body)
	require.Equal(t, "1-2/3", headers.Get("Content-Range"))

	// The same as a GET: the arguments are the parameters that are not
	// filters, so id=gt.1 is a filter and min_id=1 an argument.
	status, _, body = send(t, f.rest, http.MethodGet, titles+"?min_id=1&id=gt.1&id=lt.4&title=like.*2&select=title", f.svc, nil, "")
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"title":"a2"}]`, body)

	// not.in, or, and a column renamed by select.
	status, _, body = send(t, f.rest, http.MethodGet, titles+"?min_id=1&id=not.in.(1,2)&or=(title.eq.b1,title.eq.zz)&select=name:title", f.svc, nil, "")
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"name":"b1"}]`, body)

	// A function that returns rows of a table runs as the caller, so the row
	// rule decides which rows it sees.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_mine?select=id,title&order=id", f.a, nil, `{}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":1,"title":"a1"},{"id":2,"title":"a2"}]`, body)
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_mine?select=id&order=id", f.b, nil, `{}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":3},{"id":4}]`, body)
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_mine", f.anon, nil, `{}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[]`, body)
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_mine?select=id&order=id", f.svc, nil, `{}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[{"id":1},{"id":2},{"id":3},{"id":4}]`, body)

	// One row of a table, and one row of OUT arguments, are an object.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_first", f.a, nil, `{"min_id":2}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, fmt.Sprintf(`{"id":2,"title":"a2","owner":%q}`, userA), body)
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_pair", f.a, nil, `{"n":5}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `{"low":4,"high":6}`, body)

	// single(): a set of exactly one row is that object; any other count is
	// PGRST116.
	one := map[string]string{"Accept": "application/vnd.pgrst.object+json"}
	status, _, body = send(t, f.rest, http.MethodPost, titles+"?id=eq.2", f.a, one, `{"min_id":1}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `{"id":2,"title":"a2"}`, body)
	status, _, body = send(t, f.rest, http.MethodPost, titles, f.a, one, `{"min_id":1}`)
	require.Equal(t, http.StatusNotAcceptable, status, body)
	require.Equal(t, "PGRST116", refusalOf(t, body)["code"])
}

func TestPostgRESTCall_aSetIsCutAtThePageAndMS100AboveIt(t *testing.T) {
	f := newCallFixture(t, func(c *config.Prest) { c.PGMaxPageSize = 3 })

	// A set longer than the page, with no limit asked. Expected: the page.
	status, headers, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_nums", f.a, map[string]string{"Prefer": "count=exact"}, `{"n":10}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[1,2,3]`, body)
	require.Equal(t, "0-2/10", headers.Get("Content-Range"))

	// A limit above the page is refused, as a table read's is.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_nums?limit=4", f.a, nil, `{"n":10}`)
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, "MS100", refusalOf(t, body)["code"])
}

func TestPostgRESTCall_aFunctionThatChangesRowsAsTheCaller(t *testing.T) {
	f := newCallFixture(t)

	// rpc('rest_pgc_rename'): VOLATILE, so POST commits the change.
	status, _, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_rename", f.a, nil, `{"item":1,"new_title":"a1 renamed"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, "1", body)
	require.Equal(t, []string{"1:a1 renamed", "2:a2", "3:b1", "4:b2"}, theShelf(t, f.db))

	// Another User's row is not the caller's to change: the row rule hides it
	// from the function, and it changed none.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_rename", f.a, nil, `{"item":3,"new_title":"stolen"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, "0", body)
	require.Equal(t, []string{"1:a1 renamed", "2:a2", "3:b1", "4:b2"}, theShelf(t, f.db))

	// The reader holds no write grant, so the function is refused by the
	// Database: 401 and the Database's own words.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_rename", f.anon, nil, `{"item":1,"new_title":"anon"}`)
	require.Equal(t, http.StatusUnauthorized, status, body)
	require.Equal(t, "42501", refusalOf(t, body)["code"])

	// tx=rollback runs it and rolls it back.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_rename", f.a, map[string]string{"Prefer": "tx=rollback"}, `{"item":2,"new_title":"never"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, "1", body)
	require.Equal(t, []string{"1:a1 renamed", "2:a2", "3:b1", "4:b2"}, theShelf(t, f.db))
}

func TestPostgRESTCall_aGetRunsReadOnlySoAFunctionThatWritesIs405(t *testing.T) {
	f := newCallFixture(t)

	// RpcSpec.hs, "only for GET rpc / should fail on mutating procs": 405.
	status, _, body := send(t, f.rest, http.MethodGet, "/rest/v1/rpc/rest_pgc_rename?item=1&new_title=get", f.a, nil, "")
	require.Equal(t, http.StatusMethodNotAllowed, status, body)
	require.Equal(t, "25006", refusalOf(t, body)["code"])
	status, _, body = send(t, f.rest, http.MethodHead, "/rest/v1/rpc/rest_pgc_rename?item=1&new_title=get", f.a, nil, "")
	require.Equal(t, http.StatusMethodNotAllowed, status, body)
	require.Equal(t, []string{"1:a1", "2:a2", "3:b1", "4:b2"}, theShelf(t, f.db))

	// A VOLATILE function that writes nothing is not refused: the transaction
	// is what refuses, as PostgREST's is.
	status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/rpc/rest_pgc_stamp", f.a, nil, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, `"stamped"`, body)
}

func TestPostgRESTCall_aFunctionTheCallerMayNotRunIsRefused(t *testing.T) {
	f := newCallFixture(t)

	// The reader: 401, 42501, the Database's words. A User: runs it.
	status, _, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_secret", f.anon, nil, "")
	require.Equal(t, http.StatusUnauthorized, status, body)
	refusal := refusalOf(t, body)
	require.Equal(t, "42501", refusal["code"])
	require.Contains(t, refusal["message"], "permission denied for function rest_pgc_secret")
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_secret", f.a, nil, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, `"secret"`, body)
	// The role the User's token names, with no grant, is 403.
	exec(t, f.db, `REVOKE EXECUTE ON FUNCTION public.rest_pgc_secret() FROM `+signedIn)
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_secret", f.a, nil, "")
	require.Equal(t, http.StatusForbidden, status, body)
	require.Equal(t, "42501", refusalOf(t, body)["code"])
}

func TestPostgRESTCall_aFunctionThatIsNotThereIsPGRST202WithPostgRESTsHint(t *testing.T) {
	f := newCallFixture(t)

	// A misspelt name: the closest name is the hint.
	status, _, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_ad", f.a, nil, `{"a":1,"b":2}`)
	require.Equal(t, http.StatusNotFound, status, body)
	refusal := refusalOf(t, body)
	require.Equal(t, "PGRST202", refusal["code"])
	require.Equal(t, "Could not find the function public.rest_pgc_ad(a, b) in the schema cache", refusal["message"])
	require.Equal(t, "Searched for the function public.rest_pgc_ad with parameters a, b or with a single unnamed json/jsonb parameter, but no matches were found in the schema cache.", refusal["details"])
	require.Equal(t, "Perhaps you meant to call the function public.rest_pgc_add", refusal["hint"])

	// The right name with the wrong argument names: the hint names the
	// arguments the function takes.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_add", f.a, nil, `{"a":1,"c":2}`)
	require.Equal(t, http.StatusNotFound, status, body)
	refusal = refusalOf(t, body)
	require.Equal(t, "PGRST202", refusal["code"])
	require.Equal(t, "Perhaps you meant to call the function public.rest_pgc_add(a, b)", refusal["hint"])

	// A GET says nothing of a single unnamed parameter; no arguments is "without parameters".
	status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/rpc/zzz_nothing_like_it", f.a, nil, "")
	require.Equal(t, http.StatusNotFound, status, body)
	refusal = refusalOf(t, body)
	require.Equal(t, "Could not find the function public.zzz_nothing_like_it without parameters in the schema cache", refusal["message"])
	require.Equal(t, "Searched for the function public.zzz_nothing_like_it without parameters, but no matches were found in the schema cache.", refusal["details"])
	require.Nil(t, refusal["hint"])

	// Overloads the argument names cannot tell apart are PGRST203, 300.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_same", f.a, nil, `{"a":1}`)
	require.Equal(t, http.StatusMultipleChoices, status, body)
	refusal = refusalOf(t, body)
	require.Equal(t, "PGRST203", refusal["code"])
	require.Equal(t, "Could not choose the best candidate function between: public.rest_pgc_same(a => bigint), public.rest_pgc_same(a => integer)", refusal["message"])
	require.Equal(t, "Try renaming the parameters or the function itself in the database so function overloading can be resolved", refusal["hint"])

	// Overloads the names tell apart are not ambiguous.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_both", f.a, nil, `{"a":1}`)
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, `"one"`, body)
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_both", f.a, nil, `{"a":1,"b":2}`)
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, `"two"`, body)
}

func TestPostgRESTCall_aFunctionTakesTheWholeBody(t *testing.T) {
	f := newCallFixture(t)

	// Prefer: params=single-object hands a function of one json argument the
	// whole body, whatever its keys.
	single := map[string]string{"Prefer": "params=single-object"}
	status, _, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_echo", f.a, single, `{"x":[1,2],"y":"z"}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `{"x":[1,2],"y":"z"}`, body)
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_echo", f.a, single, `[1,2,3]`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `[1,2,3]`, body)
	// ... and a function that takes more than one argument is not found.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_add", f.a, single, `{"a":1,"b":2}`)
	require.Equal(t, http.StatusNotFound, status, body)
	refusal := refusalOf(t, body)
	require.Equal(t, "Could not find the function public.rest_pgc_add in the schema cache", refusal["message"])
	require.Equal(t, "Searched for the function public.rest_pgc_add with a single json/jsonb parameter, but no matches were found in the schema cache.", refusal["details"])
	require.Nil(t, refusal["hint"])

	// Without it, a function of one unnamed json argument is called with the body.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_unnamed", f.a, nil, `{"anything":true}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `{"anything":true}`, body)
	// A named jsonb argument is still called by its name.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_echo", f.a, nil, `{"j":{"k":1}}`)
	require.Equal(t, http.StatusOK, status, body)
	require.JSONEq(t, `{"k":1}`, body)
}

