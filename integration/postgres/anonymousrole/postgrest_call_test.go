func TestPostgRESTCall_otherMethodsAndShapesAreRefusedByName(t *testing.T) {
	f := newCallFixture(t)

	// RpcSpec.hs, "unsupported method": 405 and PGRST101.
	for _, method := range []string{http.MethodDelete, http.MethodPatch, http.MethodPut} {
		status, _, body := send(t, f.rest, method, "/rest/v1/rpc/rest_pgc_hello", f.a, nil, "")
		require.Equal(t, http.StatusMethodNotAllowed, status, method)
		refusal := refusalOf(t, body)
		require.Equal(t, "PGRST101", refusal["code"])
		require.Equal(t, "Cannot use the "+method+" method on RPC", refusal["message"])
	}
	// An embedded table in the select, and columns, are not answered.
	status, _, body := send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_mine?select=*,other(*)", f.a, nil, `{}`)
	require.Equal(t, http.StatusBadRequest, status, body)
	require.Equal(t, "PGRST100", refusalOf(t, body)["code"])
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_mine?columns=a", f.a, nil, `{}`)
	require.Equal(t, http.StatusBadRequest, status, body)
	// A body that is not JSON, and a JSON array where the arguments are named.
	for _, bad := range []string{`not json`, `[{"a":1,"b":2}]`, `42`} {
		status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_add", f.a, nil, bad)
		require.GreaterOrEqual(t, status, 400, bad)
		require.Less(t, status, 500, bad)
		require.NotEmpty(t, body)
	}
	// A schema other than public.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/rest_pgc_hello", f.a, map[string]string{"Content-Profile": "private"}, "")
	require.Equal(t, http.StatusNotAcceptable, status, body)
	require.Equal(t, "PGRST106", refusalOf(t, body)["code"])
	// A name that is not a plain name never reaches the Database.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/pg_sleep%28100%29", f.a, nil, "")
	require.Equal(t, http.StatusBadRequest, status, body)
	// A function of pg_catalog is not one the address serves.
	status, _, body = send(t, f.rest, http.MethodPost, "/rest/v1/rpc/pg_sleep", f.a, nil, `{"seconds":1}`)
	require.Equal(t, http.StatusNotFound, status, body)
	require.Equal(t, "PGRST202", refusalOf(t, body)["code"])
}
