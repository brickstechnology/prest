package anonymousrole_test

// miniship (miniship-cloud#1890, ADR 0075): GET /rest/v1/, the address
// supabase-js's getOpenApiSpec() reads, against a live Postgres.
//
// A Supabase hosted Project answers it to a secret key (service_role) with
// PostgREST 14's Swagger 2.0 document, and to the publishable (anon) key with
// 403 "Access to schema is forbidden" (changelog 42949, 17 February 2026). The
// document lists what the calling role may touch (openapi-mode
// follow-privileges), so a table or function the role holds nothing on is
// absent. The expected shapes were checked against a PostgREST v14.18 running
// on the same rows.

import (
	"database/sql"
	"encoding/json"
	"fmt"
	"net/http"
	"testing"

	"github.com/stretchr/testify/require"
)

const (
	secretRole = "service_role"
	oaPosts    = "rest_oa_posts"
	oaPeople   = "rest_oa_people"
	oaHidden   = "rest_oa_hidden"
	oaRecent   = "rest_oa_recent"
)

// stageOpenAPI makes the schema the document describes. service_role holds
// everything but rest_oa_hidden and rest_oa_secret; the signed-in role reads
// the posts only.
//
//	rest_oa_people  (id PK, name)                      service_role: all
//	rest_oa_posts   (id PK, title NOT NULL, author_id FK -> people.id, tags, meta, mood)
//	rest_oa_recent  view over the posts                service_role: select
//	rest_oa_hidden  no grant to service_role
//	rest_oa_add(a, b default), rest_oa_stamp() VOLATILE, rest_oa_secret() no EXECUTE
func stageOpenAPI(t *testing.T, db *sql.DB) {
	t.Helper()
	drop := fmt.Sprintf(`
		DROP VIEW IF EXISTS public.%[3]s;
		DROP TABLE IF EXISTS public.%[1]s, public.%[2]s, public.%[4]s CASCADE;
		DROP TYPE IF EXISTS public.rest_oa_mood;
		DROP FUNCTION IF EXISTS public.rest_oa_add(int, int), public.rest_oa_stamp(), public.rest_oa_secret();`,
		oaPosts, oaPeople, oaRecent, oaHidden)
	exec(t, db, drop)
	t.Cleanup(func() { exec(t, db, drop) })
	exec(t, db, fmt.Sprintf(`
		DO $$ BEGIN
			IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '%[6]s') THEN
				CREATE ROLE %[6]s NOLOGIN BYPASSRLS;
			END IF;
		END $$;
		GRANT %[6]s TO %[7]s;
		CREATE TYPE public.rest_oa_mood AS ENUM ('ok', 'sad');
		CREATE TABLE public.%[2]s (id integer PRIMARY KEY, name text);
		COMMENT ON TABLE public.%[2]s IS 'People
who write';
		CREATE TABLE public.%[1]s (
			id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			title varchar(40) NOT NULL DEFAULT 'untitled',
			author_id integer REFERENCES public.%[2]s (id),
			tags text[],
			meta jsonb,
			mood public.rest_oa_mood,
			views bigint NOT NULL DEFAULT 0);
		COMMENT ON COLUMN public.%[1]s.title IS 'The headline';
		CREATE VIEW public.%[3]s AS SELECT id, title FROM public.%[1]s WHERE views > 10;
		CREATE TABLE public.%[4]s (id integer PRIMARY KEY);
		GRANT ALL ON public.%[1]s, public.%[2]s TO %[6]s;
		GRANT SELECT ON public.%[3]s TO %[6]s;
		GRANT SELECT ON public.%[1]s TO %[5]s;

		CREATE FUNCTION public.rest_oa_add(a int, b int DEFAULT 1) RETURNS int LANGUAGE sql IMMUTABLE AS $$ SELECT a + b $$;
		CREATE FUNCTION public.rest_oa_stamp() RETURNS text LANGUAGE sql VOLATILE AS $$ SELECT 'stamped' $$;
		CREATE FUNCTION public.rest_oa_secret() RETURNS text LANGUAGE sql AS $$ SELECT 'secret' $$;
		REVOKE EXECUTE ON FUNCTION public.rest_oa_secret() FROM PUBLIC;
	`, oaPosts, oaPeople, oaRecent, oaHidden, signedIn, secretRole, login))
}

func newOpenAPIFixture(t *testing.T) (callFixture, string) {
	t.Helper()
	cfg, db := needsPostgres(t)
	stageFunctions(t, db)
	stageOpenAPI(t, db)
	install := newInstall(t)
	pool := newProjectPool(t, alias)
	f := callFixture{
		db:   db,
		rest: restForTheSDK(t, cfg, install, pool),
		a:    userToken(t, pool.private, userA),
		anon: projectToken(t, install.private, reader, alias),
		svc:  projectToken(t, install.private, secretRole, alias),
	}
	return f, projectToken(t, install.private, secretRole, "prj_another")
}

func openAPIDoc(t *testing.T, body string) map[string]any {
	t.Helper()
	var doc map[string]any
	require.NoError(t, json.Unmarshal([]byte(body), &doc), body)
	return doc
}

func TestPostgRESTOpenAPI_theSecretKeyGetsPostgRESTsDocument(t *testing.T) {
	f, _ := newOpenAPIFixture(t)
	oa := map[string]string{"Accept": "application/openapi+json"}

	// getOpenApiSpec(). Expected: 200 and the Swagger 2.0 document, in the type
	// PostgREST writes it in.
	status, headers, body := send(t, f.rest, http.MethodGet, "/rest/v1/", f.svc, oa, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Equal(t, "application/openapi+json; charset=utf-8", headers.Get("Content-Type"))
	doc := openAPIDoc(t, body)
	require.Equal(t, "2.0", doc["swagger"])
	require.Equal(t, "14.18", doc["info"].(map[string]any)["version"])
	require.Equal(t, "/", doc["basePath"])

	defs := doc["definitions"].(map[string]any)
	paths := doc["paths"].(map[string]any)

	// The tables and the view the role holds a privilege on are there, and a
	// table it holds nothing on is not.
	require.Contains(t, defs, oaPosts)
	require.Contains(t, defs, oaPeople)
	require.Contains(t, defs, oaRecent)
	require.NotContains(t, defs, oaHidden)
	require.NotContains(t, paths, "/"+oaHidden)
	require.NotContains(t, doc["parameters"], "body."+oaHidden)

	// The columns: types and formats, required, default, enum, length, and the
	// notes PostgREST writes for a key.
	posts := defs[oaPosts].(map[string]any)
	require.Equal(t, "object", posts["type"])
	require.Equal(t, []any{"id", "title", "views"}, posts["required"])
	props := posts["properties"].(map[string]any)
	require.Equal(t, map[string]any{"format": "int32", "type": "integer", "description": "Note:\nThis is a Primary Key.<pk/>"}, props["id"])
	require.Equal(t, map[string]any{
		"format": "character varying", "type": "string", "maxLength": float64(40), "default": "untitled", "description": "The headline",
	}, props["title"])
	require.Equal(t, map[string]any{
		"format": "int32", "type": "integer",
		"description": "Note:\nThis is a Foreign Key to `" + oaPeople + ".id`.<fk table='" + oaPeople + "' column='id'/>",
	}, props["author_id"])
	require.Equal(t, map[string]any{"format": "text[]", "type": "array", "items": map[string]any{"type": "string"}}, props["tags"])
	require.Equal(t, map[string]any{"format": "jsonb"}, props["meta"])
	require.Equal(t, map[string]any{"format": "public.rest_oa_mood", "type": "string", "enum": []any{"ok", "sad"}}, props["mood"])
	require.Equal(t, map[string]any{"format": "int64", "type": "integer", "default": float64(0)}, props["views"])
	// A view carries the primary key of its table, as PostgREST reads it from
	// the view's rewrite rule.
	require.Equal(t, "Note:\nThis is a Primary Key.<pk/>", defs[oaRecent].(map[string]any)["properties"].(map[string]any)["id"].(map[string]any)["description"])
	require.Equal(t, "People\nwho write", defs[oaPeople].(map[string]any)["description"])

	// A table has every verb. The view is a simple one, which Postgres lets be
	// written, so it has them too.
	for _, verb := range []string{"get", "post", "patch", "delete"} {
		require.Contains(t, paths["/"+oaPosts], verb)
	}
	require.Contains(t, paths["/"+oaRecent], "get")
	people := paths["/"+oaPeople].(map[string]any)["get"].(map[string]any)
	require.Equal(t, "People", people["summary"])
	require.Equal(t, "who write", people["description"])

	// An rpc function the role may execute: GET and POST for one that is not
	// volatile, POST alone for one that is, and none for one it may not run.
	add := paths["/rpc/rest_oa_add"].(map[string]any)
	require.Contains(t, add, "get")
	args := add["post"].(map[string]any)["parameters"].([]any)[0].(map[string]any)["schema"].(map[string]any)
	require.Equal(t, []any{"a"}, args["required"])
	require.Equal(t, map[string]any{"format": "int32", "type": "integer"}, args["properties"].(map[string]any)["b"])
	require.NotContains(t, paths["/rpc/rest_oa_stamp"], "get")
	require.Contains(t, paths["/rpc/rest_oa_stamp"], "post")
	require.NotContains(t, paths, "/rpc/rest_oa_secret")

	// HEAD: the headers, no body.
	status, headers, body = send(t, f.rest, http.MethodHead, "/rest/v1/", f.svc, oa, "")
	require.Equal(t, http.StatusOK, status)
	require.Empty(t, body)
	require.Equal(t, "application/openapi+json; charset=utf-8", headers.Get("Content-Type"))

	// supabase-js sends no other Accept, but application/json and a bare call
	// are answered too; text/csv is not (Plan.hs, inspectPlan).
	for _, accept := range []string{"application/json", "*/*", ""} {
		headers := map[string]string{}
		if accept != "" {
			headers["Accept"] = accept
		}
		status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/", f.svc, headers, "")
		require.Equal(t, http.StatusOK, status, accept+body)
	}
	status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/", f.svc, accepting("text/csv"), "")
	require.Equal(t, http.StatusNotAcceptable, status, body)
	require.Equal(t, "PGRST107", refusalOf(t, body)["code"])
}

func TestPostgRESTOpenAPI_everyOtherKeyIsRefusedAsSupabaseRefusesIt(t *testing.T) {
	f, anotherProject := newOpenAPIFixture(t)
	oa := accepting("application/openapi+json")
	want := `{"message":"Access to schema is forbidden","hint":"Accessing the schema via the Data API is only allowed using a secret API key."}`

	// The publishable key (the gateway's anon token), a signed-in User's token
	// and a call with no token: 403 and Supabase's two fields.
	for name, bearer := range map[string]string{"anon key": f.anon, "signed-in User": f.a, "no token": ""} {
		status, headers, body := send(t, f.rest, http.MethodGet, "/rest/v1/", bearer, oa, "")
		require.Equal(t, http.StatusForbidden, status, name+body)
		require.JSONEq(t, want, body, name)
		require.Equal(t, "application/json; charset=utf-8", headers.Get("Content-Type"), name)
	}

	// A secret key of another Project is refused as for every address
	// (PGRST301), before it could be a document.
	status, _, body := send(t, f.rest, http.MethodGet, "/rest/v1/", anotherProject, oa, "")
	require.Equal(t, http.StatusUnauthorized, status, body)
	require.Equal(t, "PGRST301", refusalOf(t, body)["code"])
}

func TestPostgRESTOpenAPI_theDocumentFollowsTheRolesGrants(t *testing.T) {
	f, _ := newOpenAPIFixture(t)
	oa := accepting("application/openapi+json")

	// The document is read in the caller's own transaction, so what the role
	// holds is what is listed. Take the posts away from service_role and the
	// table leaves the document; give it back and it returns.
	exec(t, f.db, fmt.Sprintf(`REVOKE ALL ON public.%s FROM %s`, oaPeople, secretRole))
	status, _, body := send(t, f.rest, http.MethodGet, "/rest/v1/", f.svc, oa, "")
	require.Equal(t, http.StatusOK, status, body)
	defs := openAPIDoc(t, body)["definitions"].(map[string]any)
	require.NotContains(t, defs, oaPeople)
	require.Contains(t, defs, oaPosts)
	// With the table gone from the document, the key into it carries no note.
	require.NotContains(t, defs[oaPosts].(map[string]any)["properties"].(map[string]any)["id"].(map[string]any)["description"], "Foreign")

	// A column privilege alone puts a table in the document, as PostgREST's
	// has_any_column_privilege does.
	exec(t, f.db, fmt.Sprintf(`GRANT SELECT (id) ON public.%s TO %s`, oaPeople, secretRole))
	status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/", f.svc, oa, "")
	require.Equal(t, http.StatusOK, status, body)
	require.Contains(t, openAPIDoc(t, body)["definitions"], oaPeople)

	// A function the role may no longer run leaves the paths.
	exec(t, f.db, fmt.Sprintf(`REVOKE EXECUTE ON FUNCTION public.rest_oa_add(int, int) FROM PUBLIC, %s`, secretRole))
	status, _, body = send(t, f.rest, http.MethodGet, "/rest/v1/", f.svc, oa, "")
	require.Equal(t, http.StatusOK, status, body)
	require.NotContains(t, openAPIDoc(t, body)["paths"], "/rpc/rest_oa_add")
}
